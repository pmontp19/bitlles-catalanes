const GLYPHS = {};
for (const [k, rows] of Object.entries(RAW)) {
  const pts = [];
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === '#') pts.push([x, y]); }));
  GLYPHS[k] = { w: rows[0].length, pts };
}
for (const [k, [base, extra]] of Object.entries(ACC)) {
  GLYPHS[k] = { w: GLYPHS[base].w, pts: [...GLYPHS[base].pts, ...extra] };
}

export const LINE_H = 10;

function norm(str) {
  return String(str).toUpperCase().replace(/L·L/g, 'L·L');
}

export function textWidth(str, scale = 1) {
  str = norm(str);
  let w = 0;
  for (const ch of str) { const g = GLYPHS[ch] || GLYPHS['?']; w += (g.w + 1) * scale; }
  return Math.max(0, w - scale);
}

// Dibuixa text. y = part superior de les majúscules.
export function drawText(ctx, str, x, y, color, opts = {}) {
  const scale = opts.scale || 1;
  str = norm(str);
  const w = textWidth(str, scale);
  if (opts.align === 'center') x -= Math.floor(w / 2);
  else if (opts.align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  if (opts.shadow) drawText(ctx, str, x + scale, y + scale, opts.shadow, { scale });
  ctx.fillStyle = color;
  for (const ch of str) {
    const g = GLYPHS[ch] || GLYPHS['?'];
    for (const [px, py] of g.pts) ctx.fillRect(x + px * scale, y + py * scale, scale, scale);
    x += (g.w + 1) * scale;
  }
  return w;
}

export function wrap(str, maxW, scale = 1) {
  const out = [];
  for (const para of String(str).split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const w of words) {
      const t = line ? line + ' ' + w : w;
      if (textWidth(t, scale) > maxW && line) { out.push(line); line = w; }
      else line = t;
    }
    out.push(line);
  }
  return out;
}
